#!/usr/bin/env python3
"""Generate Unity client protobuf C# classes from the shared client protocol.

Run from the Unity client directory:
    python tools/gen-proto-csharp.py

By default, this script reads ../../protocol/cspb and writes generated files to
Assets/Scripts/Proto/Generated.  It deliberately excludes pfpb and sspb because
those are platform/server-internal protocols, not the client-to-Gate contract.

The shared source contains repeated basenames (for example, several req.proto
and ack.proto files).  protoc derives C# reflection and output names from the
source basename, so generating the files directly would collide.  The script
creates a temporary flat copy with unique names and rewrites local imports
before invoking protoc. Client classes are generated directly from the shared IDL;
server-internal request headers are deliberately not injected into Unity messages.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CLIENT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PROTO_ROOT = CLIENT_ROOT.parent / "protocol" / "cspb"
DEFAULT_OUTPUT = CLIENT_ROOT / "Assets" / "Scripts" / "Proto" / "Generated"
GENERATED_HEADER = "Generated by the protocol buffer compiler"
IMPORT_PATTERN = re.compile(r'(\bimport\s+")([^"]+)("\s*;)')
# protoc 36.0 does not escape a lower-case `event` message name in generated
# C#.  Apply this only to the temporary client copy; shared IDL remains intact.
C_SHARP_RESERVED_MESSAGE_RENAMES = {"event": "Event"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--proto-root",
        type=Path,
        default=DEFAULT_PROTO_ROOT,
        help=f"client .proto root (default: {DEFAULT_PROTO_ROOT})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"C# output directory (default: {DEFAULT_OUTPUT})",
    )
    parser.add_argument(
        "--no-clean",
        action="store_true",
        help="do not remove earlier protobuf compiler output before generating",
    )
    return parser.parse_args()


def remove_generated_files(proto_output_root: Path) -> int:
    """Remove only existing protoc C# output, preserving handwritten code."""
    removed = 0
    if not proto_output_root.exists():
        return removed

    for source in proto_output_root.rglob("*.cs"):
        try:
            is_generated = GENERATED_HEADER in source.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if not is_generated:
            continue
        source.unlink()
        meta = source.with_suffix(source.suffix + ".meta")
        if meta.exists():
            meta.unlink()
        removed += 1
    return removed


def rewrite_csharp_reserved_message_names(text: str) -> str:
    """Rename reserved C# message identifiers in the temporary proto copy only."""
    for original, replacement in C_SHARP_RESERVED_MESSAGE_RENAMES.items():
        # Rename the message declaration and fields whose type is that message.
        text = re.sub(
            rf"(\bmessage\s+){re.escape(original)}(\s*\{{)",
            rf"\g<1>{replacement}\g<2>",
            text,
        )
        text = re.sub(
            rf"(\b(?:repeated\s+|optional\s+|required\s+)?){re.escape(original)}(\s+[A-Za-z_]\w*\s*=)",
            rf"\g<1>{replacement}\g<2>",
            text,
        )
    return text


def make_flat_proto_copy(proto_root: Path, staging_root: Path) -> list[Path]:
    """Copy source files under unique names and rewrite imports to those names."""
    source_files = sorted(proto_root.rglob("*.proto"))
    if not source_files:
        raise ValueError(f"no .proto files found in {proto_root}")

    # Protocol imports are relative to the shared protocol root, e.g.
    # cspb/comm/error.proto.  Build both that key and a cspb-relative key.
    shared_root = proto_root.parent
    renamed: dict[str, str] = {}
    for source in source_files:
        shared_rel = source.relative_to(shared_root).as_posix()
        local_rel = source.relative_to(proto_root).as_posix()
        unique_name = shared_rel.removesuffix(".proto").replace("/", "_") + ".proto"
        renamed[shared_rel] = unique_name
        renamed[local_rel] = unique_name

    staged_files: list[Path] = []
    for source in source_files:
        shared_rel = source.relative_to(shared_root).as_posix()
        destination = staging_root / renamed[shared_rel]
        text = source.read_text(encoding="utf-8")
        text = rewrite_csharp_reserved_message_names(text)

        def rewrite_import(match: re.Match[str]) -> str:
            imported = match.group(2)
            if imported not in renamed:
                raise ValueError(
                    f"{shared_rel} imports {imported}, which is outside the client protocol root"
                )
            return f'{match.group(1)}{renamed[imported]}{match.group(3)}'

        destination.write_text(IMPORT_PATTERN.sub(rewrite_import, text), encoding="utf-8")
        staged_files.append(destination)
    return staged_files


def main() -> None:
    args = parse_args()
    proto_root = args.proto_root.resolve()
    output = args.output.resolve()

    if not proto_root.is_dir():
        sys.exit(f"client protocol directory does not exist: {proto_root}")

    output.parent.mkdir(parents=True, exist_ok=True)
    if not args.no_clean:
        removed = remove_generated_files(output.parent)
        if removed:
            print(f"removed {removed} earlier generated C# file(s)")
    output.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="cspb-csharp-") as temporary_directory:
        staging_root = Path(temporary_directory)
        staged_files = make_flat_proto_copy(proto_root, staging_root)
        command = [
            "protoc",
            f"--proto_path={staging_root}",
            f"--csharp_out={output}",
            *map(str, staged_files),
        ]
        print(" ".join(map(str, command)))
        subprocess.run(command, check=True)

    generated = sorted(output.glob("*.cs"))
    print(f"generated {len(generated)} C# protobuf file(s) in {output}")


if __name__ == "__main__":
    main()
